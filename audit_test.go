const auditGolangciYML = `version: "2"
linters:
  default: none
  enable:
    - errcheck
    - govet
  disable:
    - gosec
  exclusions:
    presets:
      - std-error-handling
      - comments
    rules:
      - path: _test\.go
        linters:
          - errcheck
    paths:
      - legacy/
severity:
  default: info
`

// One tree with every kind audit lists, and one of each it must not.
func TestAudit(t *testing.T) {
	isolateHome(t)
	root := writeFixture(t, map[string]string{
		"go.mod": "module example.com/x\n\ngo 1.27\n\nreplace example.com/y => ../y\n\nreplace (\n\texample.com/z v1.0.0 => example.com/zfork v1.0.1 // fork\n)\n",
		"a.go": `package x

import "os"

func A() {
	os.Remove("a") //nolint
	os.Remove("b") //nolint:errcheck,gosec // best effort
	//lint:ignore SA4006 kept for the debugger
	x := 1
	_ = x
	s := "//nolint inside a string is not a directive"
	_ = s
}
`,
		"a_test.go":      "package x\n",
		"b.go":           "//lint:file-ignore U1000 generated stubs\n\npackage x\n",
		"gen.go":         "// Code generated by hand. DO NOT EDIT.\n\npackage x\n\nvar _ = 1 //nolint\n",
		"testdata/t.go":  "package t //nolint\n",
		".gochecks.json": `{"linters": false, "exclude": ["*_gen.go"]}`,
		".golangci.yml":  auditGolangciYML,
		"Makefile":       "BIN := gocheck\nexport GOWORK=off\n\ncheck: vet\n\t./$(BIN) check .\n\nvet:\n\tgo vet ./...\n",
		"Dockerfile":     "FROM golang\nRUN GOWORK=off go build ./...\n",
		"ok/Makefile":    "GC = gochecks\ncheck: lint\nlint:\n\t$(GC) check --no-apply .\n",
		"none/Makefile":  "check:\n\tgo vet ./...\n",
		"sub/go.mod":     "module example.com/sub\n",
		"sub/s_test.go":  "package sub\n",
		"bare/go.mod":    "module example.com/bare\n",
	})
	// A real grant through allow, then one for another tree.
	for id, cwd := range map[string]string{"s1": root, "s2": t.TempDir()} {
		path, err := sessionFile("sessions", id)
		if err != nil {
			t.Fatal(err)
		}
		if err := writeJSONFile(path, sessionState{CWD: cwd, LastBlock: "abc", Count: 2}); err != nil {
			t.Fatal(err)
		}
		_ = captureStdout(t, func() {
			if code := runAllow([]string{"--session", id, "vet false positive"}); code != 0 {
				t.Fatalf("allow %s: exit %d", id, code)
			}
		})
	}

	items, err := audit(root, false)
	if err != nil {
		t.Fatal(err)
	}
	var b bytes.Buffer
	writeAudit(&b, items, root, true)
	got := b.String()
	for _, want := range []string{
		"a.go:6 nolint: all linters: no reason given\n",
		"a.go:7 nolint: errcheck,gosec: best effort\n",
		"a.go:8 lint-ignore: SA4006: kept for the debugger\n",
		"b.go:1 lint-ignore: U1000 (whole file): generated stubs\n",
		".golangci.yml golangci-config: differs from the gochecks lint profile",
		".golangci.yml golangci-config: does not enable ",
		".golangci.yml:8 golangci-config: disables gosec\n",
		".golangci.yml:12 golangci-config: exclusion preset comments\n",
		".golangci.yml:14 golangci-config: exclusion rule: path: _test\\.go; linters: errcheck\n",
		".golangci.yml:18 golangci-config: exclusion path: legacy/\n",
		".golangci.yml:19 golangci-config: severity overrides\n",
		`.gochecks.json gochecks-config: "linters": false: golangci-lint does not run`,
		`.gochecks.json gochecks-config: exclude "*_gen.go": matching files are never checked`,
		`go.mod gochecks-config: "test" is off (set in ` + filepath.Join(root, ".gochecks.json") + `): go test does not run on changed packages, and this module has tests`,
		`sub/go.mod gochecks-config: "test" is off (set in `,
		"Dockerfile:2 gowork-off: ",
		"Makefile:2 gowork-off: ",
		"go.mod:5 replace: example.com/y => ../y\n",
		"go.mod:8 replace: example.com/z v1.0.0 => example.com/zfork v1.0.1\n",
		"Makefile:4 make-check: check runs gocheck, the old name; use gochecks\n",
		"none/Makefile:1 make-check: check does not run gochecks\n",
		`allow: `,
		`stop allowed past 2 finding(s), session s1, reason "vet false positive"`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %q in:\n%s", want, got)
		}
	}
	for _, not := range []string{"inside a string", "gen.go:", "testdata", "bare/", "ok/Makefile", "session s2", "std-error-handling"} {
		if strings.Contains(got, not) {
			t.Errorf("%q should not be listed:\n%s", not, got)
		}
	}
	if strings.Count(got, " nolint: ") != 2 {
		t.Errorf("want 2 nolint items:\n%s", got)
	}

	// The profile itself is not a departure.
	edit(t, filepath.Join(root, ".golangci.yml"), lintProfile)
	items, _ = audit(root, false)
	for _, it := range items {
		if it.Kind == kindGolangci {
			t.Errorf("profile copy listed: %+v", it)
		}
	}
}

// With no .gochecks.json, test is off by default; that counts too.
func TestAuditTestOffByDefault(t *testing.T) {
	isolateHome(t)
	root := writeFixture(t, map[string]string{"go.mod": "module m\n", "m_test.go": "package m\n"})
	items, _ := audit(root, false)
	if len(items) != 1 || items[0].File != filepath.Join(root, "go.mod") || !strings.HasPrefix(items[0].Msg, `"test" is off (the default)`) {
		t.Errorf("got %+v", items)
	}
}

// SessionStart adds one line counting what audit lists.
func TestSessionStartAuditLine(t *testing.T) {
	isolateHome(t)
	root := writeFixture(t, map[string]string{
		"a.go":     "package x\n\nfunc A() {} //nolint\n\n//lint:ignore U1000 why\nfunc b() {}\n",
		"Makefile": "check:\n\tgo vet ./...\n",
	})
	r := runHookEvent(t, startEvent("s1", root))
	want := "gochecks: 2 suppression(s), 1 make check gap(s): gochecks audit --text"
	if !strings.Contains(r.out, want) {
		t.Errorf("want %q, got %+v", want, r)
	}
	if r := runHookEvent(t, startEvent("s2", t.TempDir())); r.out != "" {
		t.Errorf("nothing to list, nothing said: %+v", r)
	}
}
