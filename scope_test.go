func TestIsVendored(t *testing.T) {
	cases := []struct {
		path string
		want bool
	}{
		{"/repo/foo.go", false},
		{"/repo/vendor/github.com/x/y/z.go", true},
		{"/repo/pkg/vendor/x.go", true},
		{"/repo/vendored/x.go", false}, // must be exact segment "vendor"
		{"/repo/my_vendor/x.go", false},
	}
	for _, tc := range cases {
		if got := isVendored(tc.path); got != tc.want {
			t.Errorf("isVendored(%q) = %v, want %v", tc.path, got, tc.want)
		}
	}
}

func TestIsGenerated(t *testing.T) {
	dir := t.TempDir()
	cases := []struct {
		name    string
		content string
		want    bool
	}{
		{
			"plain.go",
			"package main\n\nfunc Foo() {}\n",
			false,
		},
		{
			"generated.go",
			"// Code generated by mockgen. DO NOT EDIT.\n\npackage main\n",
			true,
		},
		{
			"comment_after_package.go",
			"package main\n\n// Code generated by thing. DO NOT EDIT.\n",
			false, // header must be before package clause
		},
		{
			"with_build_tag.go",
			"//go:build foo\n\n// Code generated by x. DO NOT EDIT.\n\npackage main\n",
			true,
		},
	}
	for _, tc := range cases {
		path := filepath.Join(dir, tc.name)
		if err := os.WriteFile(path, []byte(tc.content), 0o644); err != nil {
			t.Fatal(err)
		}
		got, err := isGenerated(path)
		if err != nil {
			t.Errorf("isGenerated(%s): %v", tc.name, err)
			continue
		}
		if got != tc.want {
			t.Errorf("isGenerated(%s) = %v, want %v", tc.name, got, tc.want)
		}
	}
}

func TestResolveChangedFilters(t *testing.T) {
	dir := t.TempDir()
	// Real .go file, keep.
	keep := filepath.Join(dir, "keep.go")
	writeFile(t, keep, "package x\n")
	// Non-Go, drop.
	notGo := filepath.Join(dir, "readme.md")
	writeFile(t, notGo, "hi")
	// Generated, drop.
	gen := filepath.Join(dir, "gen.go")
	writeFile(t, gen, "// Code generated by x. DO NOT EDIT.\npackage x\n")
	// Vendored, drop.
	vendorDir := filepath.Join(dir, "vendor", "example.com", "pkg")
	if err := os.MkdirAll(vendorDir, 0o755); err != nil {
		t.Fatal(err)
	}
	vendored := filepath.Join(vendorDir, "v.go")
	writeFile(t, vendored, "package pkg\n")
	// Missing, drop.
	missing := filepath.Join(dir, "nope.go")

	got, err := resolveChanged([]string{keep, notGo, gen, vendored, missing, keep /* dedupe */})
	if err != nil {
		t.Fatalf("resolveChanged: %v", err)
	}
	if len(got) != 1 || !strings.HasSuffix(got[0], "keep.go") {
		t.Errorf("resolveChanged kept the wrong files: %v", got)
	}
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}
